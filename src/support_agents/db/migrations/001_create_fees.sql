CREATE TABLE IF NOT EXISTS fees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board VARCHAR(50) NOT NULL CHECK (length(btrim(board)) > 0),
    standard VARCHAR(30) NOT NULL CHECK (length(btrim(standard)) > 0),
    academic_year VARCHAR(9) NOT NULL
        CHECK (academic_year ~ '^[0-9]{4}-[0-9]{4}$')
        CHECK (
            substring(academic_year FROM 1 FOR 4)::INTEGER + 1
            = substring(academic_year FROM 6 FOR 4)::INTEGER
        ),
    fee_type VARCHAR(50) NOT NULL CHECK (length(btrim(fee_type)) > 0),
    amount NUMERIC(12, 2) NOT NULL CHECK (amount >= 0),
    currency CHAR(3) NOT NULL DEFAULT 'INR' CHECK (currency ~ '^[A-Z]{3}$'),
    billing_frequency VARCHAR(20) NOT NULL CHECK (
        billing_frequency IN ('one_time', 'monthly', 'quarterly', 'term', 'annual')
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS fees_lookup_unique
    ON fees (lower(board), lower(standard), academic_year, lower(fee_type));

CREATE INDEX IF NOT EXISTS fees_lookup_idx
    ON fees (lower(board), lower(standard), academic_year);
